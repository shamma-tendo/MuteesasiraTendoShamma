txt = "Hello, Uganda! "

# Remove spaces at the beginning and end using strip()
print(txt.strip())

# To remove spaces in the middle, you'd need to specify which spaces
# For example, removing all spaces:
print(txt.replace(" ", ""))

# Or removing specific spaces (like between Hello, and Uganda):
print(txt.replace(" ", ""))

#convert value of txt to upper case
txt = "Hello, Uganda! "
